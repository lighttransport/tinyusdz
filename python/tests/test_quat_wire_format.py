def test_pxr_can_read_tinyusdz_quat_output(tmp_path):
    """Sanity: the bytes tinyusdz writes for a quatf must be in pxr
    wire layout (imag.x, imag.y, imag.z, real). We can verify without
    invoking pxr by inspecting the raw USDC bytes."""
    s = tinyusdz.Stage()
    p = tinyusdz.Prim("Xform", name="X")
    # real=1, imag=(0.25, 0.5, 0.75) — distinct components so order
    # mistakes are obvious.
    p.set_attribute("q", (1.0, 0.25, 0.5, 0.75), dtype="quatf")
    s.add_root_prim(p)
    out = tmp_path / "q.usdc"
    s.save(str(out))
    data = out.read_bytes()
    # Find the 16-byte payload (4 floats matching 0.25, 0.5, 0.75, 1.0).
    needle = struct.pack("<ffff", 0.25, 0.5, 0.75, 1.0)
    assert needle in data, "expected pxr wire order (imag.x, imag.y, imag.z, real) in USDC bytes"